local addon = require("spec.helpers.addon")

describe("View", function()
    local ns, progress

    local function goTo(id)
        while progress:Current().id ~= id do
            progress:Done(false)
        end
    end

    before_each(function()
        ns = addon.load({ "Locale.lua", "Steps.lua", "Progress.lua", "View.lua" })
        progress = ns.Progress.New({}, ns.Steps, { log = function() end })
    end)

    it("shows S0 with the snapshot result and the log path", function()
        local view =
            ns.View.Step(progress, { snapshot = { count = 24, supported = 35 }, events = 36 })
        assert.are.equal("S0", view.id)
        assert.are.equal("Step S0 (1 of 16)", view.header)
        assert.are.equal("Login snapshot", view.title)
        assert.truthy(view.extra:find("Login snapshot (S0): 24 entries, 35 of 36", 1, true))
        assert.truthy(view.extra:find("SavedVariables\\FishingMasteryProbe.lua", 1, true))
        assert.are.equal("", view.counter)
        assert.is_false(view.buttons.start)
        assert.is_false(view.buttons.back)
        assert.truthy(view.questions:find("Q01, Q02", 1, true))
        assert.truthy(view.why:find("^Why: "))
        assert.truthy(view.prereq:find("^Needs: "))
    end)

    it("shows a pending snapshot before PLAYER_LOGIN ran", function()
        local view = ns.View.Step(progress, nil)
        assert.truthy(view.extra:find("not run yet", 1, true))
    end)

    it("shows the live counter and the Start state", function()
        goTo("S3")
        local view = ns.View.Step(progress)
        assert.are.equal("Catches: 0 / 5", view.counter)
        assert.truthy(view.state:find("Press Start", 1, true))
        assert.is_true(view.buttons.start)
        assert.is_true(view.buttons.startEnabled)
        assert.is_true(view.buttons.back)
        assert.are.equal("", view.extra)
        progress:Start()
        progress:Observe("attempt", { outcome = "catch" })
        progress:Observe("attempt", { outcome = "catch" })
        view = ns.View.Step(progress)
        assert.are.equal("Catches: 2 / 5", view.counter)
        assert.are.equal("", view.state)
        assert.is_false(view.buttons.startEnabled)
        assert.are.equal("Catches: 2 / 5", ns.View.Counter(progress))
    end)

    it("labels optional steps and steps that are already done", function()
        goTo("S11")
        local view = ns.View.Step(progress)
        assert.are.equal("Fish a school or wreckage (optional)", view.title)
        assert.is_true(view.optional)
        progress:Skip("optional")
        progress:Back()
        view = ns.View.Step(progress)
        assert.truthy(view.state:find("already marked Skipped", 1, true))
    end)

    it("explains the hand-over on S15 and the finished run", function()
        goTo("S15")
        local view = ns.View.Step(progress)
        assert.truthy(view.instruction:find("/reload", 1, true))
        assert.truthy(view.instruction:find("probe-results", 1, true))
        assert.truthy(view.extra:find("FishingMasteryProbe.lua", 1, true))
        assert.is_nil(ns.View.Counter(progress))
        progress:Done(false)
        view = ns.View.Step(progress)
        assert.truthy(view.state:find("All steps are done or skipped", 1, true))
    end)

    it("lists every step in the checklist with status and reason", function()
        progress:Done(false)
        progress:Skip("no_item")
        local lines = ns.View.Checklist(progress)
        assert.are.equal(16, #lines)
        assert.are.equal("  S0  Login snapshot - Done", lines[1].text)
        assert.are.equal("  S1  Without fishing pole - Skipped (No item)", lines[2].text)
        assert.are.equal("> S2  With fishing pole - Open", lines[3].text)
        assert.is_true(lines[3].current)
        assert.are.equal("  S12  Let a fish get away (optional) - Open", lines[13].text)
        assert.are.equal("skipped", lines[2].status)
    end)
end)
