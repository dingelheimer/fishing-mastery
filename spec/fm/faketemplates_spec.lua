-- The fakeui stubs of the templates chosen in Story 9.1 and the StatusBar frame type.
local fakeui = require("spec.helpers.fakeui")

describe("fakeui template stubs", function()
    local env

    before_each(function()
        env = fakeui.new()
    end)

    it("gives the window templates their title, portrait, close button, and inset", function()
        local window = env.CreateFrame("Frame", nil, env.UIParent, "ButtonFrameTemplate")
        window:SetTitle("Fishing Mastery")
        window:SetPortraitToAsset("icon-fishing")
        assert.are.equal("Fishing Mastery", window.TitleContainer.TitleText:GetText())
        assert.are.equal("icon-fishing", window.PortraitContainer.portrait.texture)
        assert.are.equal("InsetFrameTemplate", window.Inset.template)
        assert.is_truthy(window.Inset.Bg)
        window.CloseButton:Click()
        assert.is_false(window:IsShown())
    end)

    it("gives the side tab a checked state and the HUD frame a nine-slice", function()
        local tab = env.CreateFrame("CheckButton", nil, nil, "LargeSideTabButtonTemplate")
        assert.is_false(tab:GetChecked())
        assert.is_false(tab.SelectedTexture:IsShown())
        tab:SetChecked(true)
        assert.is_true(tab.SelectedTexture:IsShown())
        local hud = env.CreateFrame("Frame", nil, nil, "TooltipBackdropTemplate")
        hud.NineSlice:SetCenterColor(0, 0, 0, 0.8)
        assert.are.same({ 0, 0, 0, 0.8 }, hud.NineSlice.center)
    end)

    it("gives status bars a range, a value, and a color", function()
        local bar = env.CreateFrame("StatusBar")
        bar:SetMinMaxValues(0, 75)
        bar:SetValue(40)
        bar:SetStatusBarColor(1, 0.82, 0)
        assert.are.same({ 0, 75 }, { bar:GetMinMaxValues() })
        assert.are.equal(40, bar:GetValue())
        assert.are.same({ 1, 0.82, 0 }, bar.barColor)
        assert.is_nil(env.CreateFrame("Frame").SetValue)
        assert.is_false(env.IsShiftKeyDown())
    end)
end)
