-- Checks the generated zone data (FishingMastery/Data/Zones.lua, tools/build_zone_data.py):
-- coverage counts of the pinned sources, number types in every list row, the area placement
-- (subzone parents, map and instance tables), and known rows from the research doc.
local addon = require("spec.helpers.addon")

local PATH = "FishingMastery/Data/Zones.lua"

local function count(t)
    local n = 0
    for _ in pairs(t) do
        n = n + 1
    end
    return n
end

describe("FishingMastery zone data", function()
    local Zones

    setup(function()
        Zones = addon.load({ "Data\\Zones.lua" }, {}, "FishingMastery").Zones
    end)

    it("is generated from the pinned sources", function()
        local handle = assert(io.open(PATH, "rb"))
        local text = handle:read("*a")
        handle:close()
        assert.truthy(text:find("^%-%- Generated by tools/build_zone_data.py; do not edit%."))
        assert.truthy(#text < 50 * 1024, "size " .. #text)
        assert.are.same(
            { cmangos = "37eeeeb1d4", att = "e15f5d9cee", client = "1.60.1.70790" },
            Zones.meta
        )
    end)

    it("is loaded by the TOC before the modules", function()
        local files = addon.tocFiles("FishingMastery")
        local position = {}
        for i, file in ipairs(files) do
            position[file] = i
        end
        assert.is_not_nil(position["Data\\Zones.lua"])
        assert.is_true(position["Data\\Zones.lua"] < position["Context.lua"])
    end)

    it("covers the measured areas and lists", function()
        local zones, subzones, dungeons = 0, 0, 0
        for _, area in pairs(Zones.areas) do
            if area.zone then
                subzones = subzones + 1
            elseif area.instance then
                dungeons = dungeons + 1
            else
                zones = zones + 1
            end
        end
        assert.are.equal(136, count(Zones.areas))
        assert.are.equal(43, zones)
        assert.are.equal(84, subzones)
        assert.are.equal(9, dungeons)
        assert.are.equal(43, count(Zones.mapToArea))
        assert.are.equal(9, count(Zones.instanceToArea))
        assert.are.equal(33, #Zones.lists)
        local rows = 0
        for _, list in ipairs(Zones.lists) do
            rows = rows + #list
        end
        assert.are.equal(345, rows)
    end)

    it("has only numbers in the list rows", function()
        for i, list in ipairs(Zones.lists) do
            assert.is_true(#list > 0, "list " .. i)
            for _, row in ipairs(list) do
                assert.is_true(#row >= 3 and #row <= 5, "list " .. i)
                for field = 1, #row do
                    assert.are.equal("number", type(row[field]), "list " .. i)
                end
                local item, chance, group, condition, quest = unpack(row)
                assert.is_true(item > 0 and item % 1 == 0)
                assert.is_true(chance > 0 and chance <= 100, "chance " .. chance)
                assert.is_true(group >= 0 and group % 1 == 0)
                assert.is_true(
                    condition == nil or condition == 0 or condition == 322 or condition == 323
                )
                assert.is_true(quest == nil or quest == 1)
            end
        end
    end)

    it("places every area consistently", function()
        for id, area in pairs(Zones.areas) do
            assert.are.equal("number", type(id))
            assert.is_true(area.base ~= nil or area.list ~= nil, "area " .. id)
            if area.list then
                assert.is_not_nil(Zones.lists[area.list], "area " .. id)
            end
            if area.zone then
                local parent = Zones.areas[area.zone]
                assert.is_not_nil(parent, "parent of " .. id)
                assert.is_nil(parent.zone, "nested subzone " .. id)
                assert.is_nil(parent.instance, "parent of " .. id)
            end
        end
        local mapped = {}
        for map, zone in pairs(Zones.mapToArea) do
            assert.are.equal("number", type(map))
            local area = Zones.areas[zone]
            assert.is_true(area ~= nil and area.zone == nil and area.instance == nil, "map " .. map)
            mapped[zone] = true
        end
        for id, area in pairs(Zones.areas) do
            if not area.zone and not area.instance then
                assert.is_true(mapped[id], "zone without a map " .. id)
            end
        end
        local listed = 0
        for zone, kids in pairs(Zones.children) do
            assert.is_true(mapped[zone], "children of " .. zone)
            for _, kid in ipairs(kids) do
                assert.are.equal(zone, Zones.areas[kid].zone)
                listed = listed + 1
            end
        end
        assert.are.equal(84, listed)
        for instance, id in pairs(Zones.instanceToArea) do
            assert.are.equal(instance, Zones.areas[id].instance)
        end
    end)

    it("holds the known rows from the research", function()
        local areas = Zones.areas
        assert.are.equal(14, Zones.mapToArea[1411]) -- Durotar
        assert.are.equal(-70, areas[14].base)
        assert.are.equal(14, areas[367].zone) -- Sen'jin Village
        assert.are.equal(14, areas[814].zone) -- Southfury River, Durotar
        assert.are.equal(17, areas[815].zone) -- Southfury River, The Barrens
        assert.are.equal(130, areas[33].base) -- Stranglethorn Vale
        assert.are.same(
            { base = 205, list = areas[297].list, merged = true, zone = 33 },
            areas[297]
        ) -- Jaguero Isle
        assert.are.equal(330, areas[1112].base) -- Jademir Lake in Feralas (205)
        assert.are.equal(205, areas[357].base)
        assert.are.equal(1581, Zones.instanceToArea[36]) -- The Deadmines
        assert.are.equal(718, Zones.instanceToArea[43]) -- Wailing Caverns
        assert.is_nil(areas[927]) -- The Shining Strand has no own data
        assert.are.equal(130, areas[305].zone) -- North Tide's Run, own list

        -- Sen'jin Village (coast): the zero-chance Raw Brilliant Smallfish takes what the group
        -- leaves (58.8 %). Inland Durotar has its own list.
        local senjin = {}
        for _, row in ipairs(Zones.lists[areas[367].list]) do
            senjin[row[1]] = row
        end
        assert.are.same({ 6291, 58.8, 1 }, senjin[6291])
        assert.are.same({ 6289, 40, 1 }, senjin[6289])
        assert.are.same({ { 6303, 98, 1 }, { 6356, 2, 1 } }, Zones.lists[areas[14].list])

        -- Seasonal rows keep their condition IDs: 10 % reference roll, 100 % inside it.
        local seasons = {}
        for _, row in ipairs(Zones.lists[areas[16].list]) do -- Azshara
            if row[4] then
                seasons[row[4]] = row
            end
        end
        assert.are.same({ 13755, 10, 0, 322 }, seasons[322])
        assert.are.same({ 13756, 10, 0, 323 }, seasons[323])
    end)

    it("merges subzone extras into the zone list and marks partial lists", function()
        local areas, lists = Zones.areas, Zones.lists
        local function fish(list)
            local share = 0
            for _, row in ipairs(list) do
                if row[3] == 1 then
                    share = share + row[2]
                end
            end
            return share
        end
        local merged, partial = 0, 0
        for id, area in pairs(areas) do
            if area.merged then
                merged = merged + 1
                assert.is_not_nil(area.zone, "merged zone " .. id)
                -- Every row of the zone list is in the merged list.
                local rows = {}
                for _, row in ipairs(lists[area.list]) do
                    rows[table.concat(row, "/")] = true
                end
                for _, row in ipairs(lists[areas[area.zone].list]) do
                    assert.is_true(rows[table.concat(row, "/")], "area " .. id)
                end
            end
            if area.list then
                local missing = 100 - fish(lists[area.list])
                if area.partial then
                    partial = partial + 1
                    assert.is_true(math.abs(missing - area.partial) < 0.01, "area " .. id)
                else
                    assert.is_true(math.abs(missing) < 0.01, "full list " .. id)
                end
            end
        end
        assert.are.equal(13, merged)
        assert.are.equal(5, partial)
        assert.are.equal(45.4, areas[130].partial) -- Silverpine Forest
        assert.are.equal(100, areas[38].partial) -- Loch Modan: only the own-roll Loch Frenzy

        -- Jaguero Isle: Stranglethorn's fish with the seasonal rows on top.
        local seasons = 0
        for _, row in ipairs(lists[areas[297].list]) do
            seasons = seasons + ((row[4] == 322 or row[4] == 323) and 1 or 0)
        end
        assert.are.equal(2, seasons)
        assert.are.equal(#lists[areas[33].list] + 2, #lists[areas[297].list])
    end)
end)
