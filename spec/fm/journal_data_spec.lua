-- Checks the generated journal data (FishingMastery/Data/Journal.lua, tools/build_journal_data.py):
-- the measured counts of the pinned sources, number and value types in every row, that every
-- recipe uses a journal item, that grouped items are the zone data's fishing items, and known rows
-- from the Journal research doc.
local addon = require("spec.helpers.addon")

local PATH = "FishingMastery/Data/Journal.lua"
local JOURNAL_GROUPS = { fish = true, trophy = true, container = true, quest = true }
local SOURCES = { vendor = true, trainer = true, quest = true, drop = true, fishing = true }
SOURCES.guide = true

local function count(t)
    local n = 0
    for _ in pairs(t) do
        n = n + 1
    end
    return n
end

local function isId(value)
    return type(value) == "number" and value > 0 and value % 1 == 0
end

describe("FishingMastery journal data", function()
    local Journal, Zones, groupOf

    setup(function()
        local ns = addon.load({ "Data\\Zones.lua", "Data\\Journal.lua" }, {}, "FishingMastery")
        Journal, Zones = ns.Journal, ns.Zones
        groupOf = {}
        for group, ids in pairs(Journal.groups) do
            for _, id in ipairs(ids) do
                assert.is_nil(groupOf[id], "item in two groups " .. id)
                groupOf[id] = group
            end
        end
    end)

    it("is generated from the pinned sources", function()
        local handle = assert(io.open(PATH, "rb"))
        local text = handle:read("*a")
        handle:close()
        assert.truthy(text:find("^%-%- Generated by tools/build_journal_data.py; do not edit%."))
        assert.truthy(#text < 10 * 1024, "size " .. #text)
        assert.are.same(Zones.meta, Journal.meta)
    end)

    it("is loaded by the TOC after the zone data and before the modules", function()
        local position = {}
        for i, file in ipairs(addon.tocFiles("FishingMastery")) do
            position[file] = i
        end
        assert.are.equal(position["Data\\Zones.lua"] + 1, position["Data\\Journal.lua"])
        assert.is_true(position["Data\\Journal.lua"] < position["Context.lua"])
    end)

    it("groups exactly the items of the zone data's loot lists", function()
        local counts = {}
        for group, ids in pairs(Journal.groups) do
            counts[group] = #ids
            for _, id in ipairs(ids) do
                assert.is_true(isId(id), group)
            end
        end
        assert.are.same({
            fish = 28,
            trophy = 35,
            container = 18,
            quest = 7,
            potion = 11,
            junk = 6,
            other = 3,
        }, counts)
        local listed = {}
        for _, list in ipairs(Zones.lists) do
            for _, row in ipairs(list) do
                listed[row[1]] = true
                assert.is_not_nil(groupOf[row[1]], "ungrouped item " .. row[1])
            end
        end
        assert.are.equal(108, count(listed))
        assert.are.equal(108, count(groupOf))
    end)

    it("has typed recipe rows that each use a journal item", function()
        local bySkill = {}
        for spell, r in pairs(Journal.recipes) do
            assert.is_true(isId(spell))
            local skill, product, reagents, low, high, learn, source, item, quest = unpack(r)
            assert.is_true(skill == 185 or skill == 171, "skill " .. spell)
            bySkill[skill] = (bySkill[skill] or 0) + 1
            assert.is_true(isId(product))
            assert.is_true(#reagents >= 1 and #reagents <= 8)
            local usesJournal = false
            for _, reagent in ipairs(reagents) do
                assert.is_true(isId(reagent[1]) and isId(reagent[2]), "reagent " .. spell)
                usesJournal = usesJournal or JOURNAL_GROUPS[groupOf[reagent[1]]] == true
            end
            assert.is_true(usesJournal, "recipe without a journal item " .. spell)
            assert.is_true(low <= high and learn >= 1 and learn <= low, "ranks " .. spell)
            assert.is_true(SOURCES[source], "source " .. spell)
            assert.are.equal(source == "trainer", item == 0, "recipe item " .. spell)
            assert.are.equal(source == "quest", quest ~= 0)
        end
        assert.are.equal(23, count(Journal.recipes))
        assert.are.same({ [185] = 19, [171] = 4 }, bySkill)
        assert.is_nil(Journal.recipes[25662]) -- Copy of Nightfin Soup: not on a Forever line
    end)

    it("has typed gear rows", function()
        for id, g in pairs(Journal.gear) do
            local bonus, skill, level, races, source, quest, kind = unpack(g)
            assert.is_true(isId(id) and isId(bonus) and bonus <= 35, "gear " .. id)
            assert.is_true(skill >= 0 and level >= 0 and races >= 0)
            assert.is_true(SOURCES[source], "source " .. id)
            assert.are.equal(source == "quest", quest ~= 0)
            assert.is_true(kind == "gear" or kind == "lure")
        end
        assert.are.equal(10, count(Journal.gear))
        for _, unused in ipairs({ 7996, 12221, 12222 }) do
            assert.is_nil(Journal.gear[unused])
        end
    end)

    it("holds the known rows from the research", function()
        local J = Journal
        assert.are.equal("fish", groupOf[6291]) -- Raw Brilliant Smallfish
        assert.are.equal("container", groupOf[6643]) -- Bloated Smallfish
        assert.are.equal("trophy", groupOf[13917]) -- 103 Pound Mightfish
        assert.are.equal("quest", groupOf[16967]) -- Feralas Ahi
        assert.are.equal("junk", groupOf[6651]) -- Broken Wine Bottle
        assert.are.same(
            { 185, 6290, { { 6291, 1 } }, 45, 85, 1, "vendor", 6325, 0 },
            J.recipes[7751]
        )
        assert.are.same(
            { 185, 13934, { { 13893, 1 }, { 2692, 1 }, { 3713, 1 } }, 315, 355, 275, "vendor" },
            { unpack(J.recipes[18246], 1, 7) }
        )
        assert.are.equal("trainer", J.recipes[7836][7]) -- Blackmouth Oil
        assert.are.same({ 35, 300, 0, 0, "quest", 8193, "gear" }, J.gear[19970]) -- Arcanite
        assert.are.same({ 25, 100, 0, 178, "quest", 7815, "gear" }, J.gear[19022]) -- FC-5000
        assert.are.same({ 20, 100, 25, 0, "drop", 0, "gear" }, J.gear[6367]) -- Big Iron
        assert.are.same({ 25, 1, 0, 0, "guide", 0, "lure" }, J.gear[259846]) -- Wide-Brimmed Hat
        assert.are.same(
            { season = "winter", event = 35, month = 9, day = 23, hour = 1, days = 178 },
            J.seasons[13755]
        )
        assert.are.same(
            { season = "summer", event = 36, month = 3, day = 21, hour = 1, days = 187 },
            J.seasons[13756]
        )
    end)
end)
