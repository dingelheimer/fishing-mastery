"""Build FishingMastery/Data/Journal.lua from the trimmed sources in tools/data/.

Usage (repository root): python tools/build_journal_data.py

Writes the journal group of every item a fishing roll can give, the Classic recipes that use a
journal item (profession, product, reagents, color ranks, learn skill, source), the obtainable
fishing gear (bonus, required skill and level, race mask, source), the Forever-only fishing items
confirmed in Story 5.1, the fishing bonus of buff food made by a bundled recipe (guide values), and
the season rule of the seasonal fish. Fails loudly when an item fits no group, a recipe or gear
item has no source, or a buff food is not a bundled recipe's product. Only numbers, fixed keys, values from fixed
sets, and sanitized English names in comments are written. Python 3 standard library only.
"""

import os
import sys

import journal_sources as js
import zone_sources as zs
from build_zone_data import comment, number, version

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "FishingMastery", "Data", "Journal.lua")
MAX_BYTES = 10 * 1024
MAX_COLUMNS = 100

SOURCES = frozenset(["vendor", "trainer", "quest", "drop", "fishing", "guide"])
KINDS = frozenset(["gear", "lure"])
SLOTS = frozenset(["pole", "head", "feet", "hands", "line"])
RANK_KEYS = frozenset(r[0] for r in js.RANKS)

# Forever-only fishing items, confirmed on live in Story 5.1 (Journal research, "Confirmed on
# Live"). The tooltip states no number for the line; its +5 is the Wowhead guide value.
FOREVER_GEAR = {
    19971: {"bonus": 5, "skill": 150, "source": "guide", "kind": "gear", "slot": "line",
            "name": "High Test Eternium Fishing Line"},
    259846: {"bonus": 25, "skill": 1, "source": "guide", "kind": "lure", "slot": "head",
             "name": "Wide-Brimmed Fishing Hat"},
}

# Fishing buff food (new in Forever): product item -> fishing bonus and character level, from the
# beta guides and Wowhead (Fishing Mechanics, "Skill Bonuses"). Only food made by a bundled recipe
# is listed; Fillet of Frenzy and Spinefin Halibut have no known recipe or item ID yet.
FOOD = {
    6316: {"bonus": 3, "level": 5, "name": "Loch Frenzy Delight"},
    4593: {"bonus": 8, "level": 15, "name": "Bristle Whisker Catfish"},
    4594: {"bonus": 12, "level": 25, "name": "Rockscale Cod"},
    13930: {"bonus": 18, "level": 35, "name": "Filet of Redgill"},
}


# Day/night fish: CMaNGOS has no condition for them; GatherTogether claims a time window (Journal
# research, "Seasons and Day/Night"). The addon shows an unconfirmed tag next to own catches by
# server hour.
TIME_FISH = {13759: "night", 13760: "day"}  # Raw Nightfin Snapper, Raw Sunscale Salmon
TIMES = frozenset(["day", "night"])


def word(value, allowed):
    if value not in allowed:
        raise zs.DataError("unexpected value %r" % (value,))
    return '"' + value + '"'


def id_lines(ids, indent):
    """One ID per line, as StyLua formats a list that does not fit on one line."""
    return [indent + number(i) + "," for i in sorted(ids)]


def fields(pairs):
    return ", ".join("%s = %s" % (key, value) for key, value in pairs if value is not None)


def entry(key, values, name):
    """Lines of one `[key] = { values },` row with its name as a comment above. A row longer than
    the 100-column limit is expanded one value per line, the way StyLua formats it."""
    lines = ["        -- " + comment(name)]
    line = "        [%s] = { %s }," % (number(key), ", ".join(values))
    if len(line) <= MAX_COLUMNS:
        return lines + [line]
    lines.append("        [%s] = {" % number(key))
    lines.extend("            %s," % value for value in values)
    lines.append("        },")
    return lines


def build(zone_sources, sources):
    lists = zs.resolve_lists(zone_sources)
    fishing_items = {item for items in lists.values() for item, _, _, _, _ in items}
    groups = js.groups(sources, fishing_items)
    journal_items = {i for i, g in groups.items() if g in js.JOURNAL_GROUPS}
    recipes, dropped = js.recipes(sources, journal_items)
    gear, unused = js.gear(sources, fishing_items)
    for item in FOREVER_GEAR:
        if item in gear:
            raise zs.DataError("Forever item %d is already in the Classic gear" % item)
    products = {r["product"] for r in recipes.values()}
    for item in FOOD:
        if item not in products:
            raise zs.DataError("buff food %d is no bundled recipe's product" % item)
    seasons = js.seasons(sources, lists)
    for item in TIME_FISH:
        if groups.get(item) != "fish":
            raise zs.DataError("day/night fish %d is not a journal fish" % item)
    lures = js.lures(sources)
    ranks = js.ranks(sources)
    enchants = js.enchants(sources)

    out = [
        "-- Generated by tools/build_journal_data.py; do not edit. Refresh: see README, Zone Data.",
        "-- Sources: CMaNGOS classic-db %s (GPL-3.0); World of Warcraft: Forever client tables"
        % zs.CMANGOS_COMMIT[:10],
        "-- build %s from the AllTheThings exports %s (MIT)." % (zs.CLIENT_BUILD, zs.ATT_COMMIT[:10]),
        "local _, ns = ...",
        "",
        "ns.Journal = {",
        "    meta = { cmangos = %s, att = %s, client = %s },"
        % (
            version(zs.CMANGOS_COMMIT[:10], r"[0-9a-f]{10}"),
            version(zs.ATT_COMMIT[:10], r"[0-9a-f]{10}"),
            version(zs.CLIENT_BUILD, r"[0-9.]+"),
        ),
        "    -- Journal group -> item IDs of every item a Classic fishing roll can give. The journal",
        "    -- shows fish, trophy, container, quest (owner decision 2026-11-06).",
        "    groups = {",
    ]
    for group in js.GROUPS:
        ids = [i for i, g in groups.items() if g == group]
        line = "        %s = { %s }, -- %d" % (group, ", ".join(number(i) for i in sorted(ids)), len(ids))
        if len(line) <= MAX_COLUMNS:
            out.append(line)
            continue
        out.append("        %s = { -- %d" % (group, len(ids)))
        out.extend(id_lines(ids, "            "))
        out.append("        },")
    out.append("    },")
    out.append("    -- Recipe spell -> { skill line (185 Cooking, 171 Alchemy), product item, reagents")
    out.append("    -- { { itemID, count } }, yellow up to, green up to (then gray), learn skill, source,")
    out.append("    -- recipe item (0: none), quest (0: none) }")
    out.append("    recipes = {")
    for sid, r in sorted(recipes.items()):
        reagents = ", ".join("{ %s, %s }" % (number(i), number(c)) for i, c in r["reagents"])
        values = [
            number(r["skill"]),
            number(r["product"]),
            "{ " + reagents + " }",
            number(r["low"]),
            number(r["high"]),
            number(r["learn"]),
            word(r["source"], SOURCES),
            number(r.get("item", 0)),
            number(r.get("quest", 0)),
        ]
        out.extend(entry(sid, values, r["name"]))
    out.append("    },")
    out.append("    -- Fishing gear -> { bonus, fishing skill to use, character level (0: any), race mask")
    out.append("    -- (0: all), source, quest (0: none), kind (lure: a Use effect), slot }. Forever:")
    out.append("    -- Story 5.1.")
    out.append("    gear = {")
    rows = dict(gear)
    for item, g in FOREVER_GEAR.items():
        rows[item] = dict(g, level=0, races=0)
    for item, g in sorted(rows.items()):
        values = [
            number(g["bonus"]),
            number(g["skill"]),
            number(g["level"]),
            number(g["races"]),
            word(g["source"], SOURCES),
            number(g.get("quest", 0)),
            word(g.get("kind", "gear"), KINDS),
            word(g["slot"], SLOTS),
        ]
        out.extend(entry(item, values, g["name"]))
    out.append("    },")
    out.append("    -- Lure -> { bonus (guide value per enchant), fishing skill to use, race mask (0: all),")
    out.append("    -- source, quest (0: none) }")
    out.append("    lures = {")
    for item, g in sorted(lures.items()):
        values = [
            number(g["bonus"]),
            number(g["skill"]),
            number(g["races"]),
            word(g["source"], SOURCES),
            number(g.get("quest", 0)),
        ]
        out.extend(entry(item, values, g["name"]))
    out.append("    },")
    out.append("    -- Lure enchant on the pole (GetWeaponEnchantInfo) -> fishing bonus (guide values).")
    out.append("    lureEnchants = { %s },"
               % ", ".join("[%s] = %s" % (number(e), number(b))
                           for e, b in sorted(js.LURE_ENCHANTS.items())))
    out.append("    -- Fishing ranks in order: { key, rank cap, fishing skill and character level (0: any)")
    out.append("    -- to learn, source, trainer spell (0: a book), book item (0: trained) }")
    out.append("    ranks = {")
    for r in ranks:
        out.append("        { %s, %s, %s, %s, %s, %s, %s },"
                   % (word(r["key"], RANK_KEYS), number(r["cap"]), number(r["skill"]),
                      number(r["level"]), word(r["source"], SOURCES), number(r["spell"]),
                      number(r["item"])))
    out.append("    },")
    out.append("    -- Fishing enchant spell -> { bonus (guide value), Enchanting skill to learn, formula")
    out.append("    -- item, the formula's source }")
    out.append("    enchants = {")
    for spell, e in sorted(enchants.items()):
        values = [number(e["bonus"]), number(e["skill"]), number(e["formula"]),
                  word(e["source"], SOURCES)]
        out.extend(entry(spell, values, e["name"]))
    out.append("    },")
    out.append("    -- Fishing buff food -> { fishing bonus, character level, source }. Guide values")
    out.append("    -- until the aura is read in game.")
    out.append("    food = {")
    for item, f in sorted(FOOD.items()):
        values = [number(f["bonus"]), number(f["level"]), word("guide", SOURCES)]
        out.extend(entry(item, values, f["name"]))
    out.append("    },")
    out.append("    -- Day/night fish -> the window the guides claim (unconfirmed; not in CMaNGOS).")
    out.append("    times = { %s },"
               % ", ".join("[%s] = %s" % (number(i), word(w, TIMES))
                           for i, w in sorted(TIME_FISH.items())))
    out.append("    -- Seasonal fish (Classic game events): starts every year on month/day at hour")
    out.append("    -- (server time) and lasts days.")
    out.append("    seasons = {")
    for item, s in sorted(seasons.items()):
        if s["every"] != 525600:
            raise zs.DataError("season event %d is not yearly" % s["event"])
        body = fields([
            ("season", word(s["season"], frozenset(js.SEASON_EVENTS.values()))),
            ("event", number(s["event"])),
            ("month", number(s["month"])),
            ("day", number(s["day"])),
            ("hour", number(s["hour"])),
            ("days", number(s["length"] // 1440)),
        ])
        out.append("        [%s] = { %s }," % (number(item), body))
    out.append("    },")
    out.append("}")
    text = "\n".join(out) + "\n"

    summary = {
        "items": len(groups),
        "groups": {g: sum(1 for x in groups.values() if x == g) for g in js.GROUPS},
        "recipes": len(recipes),
        "bySkill": {k: sum(1 for r in recipes.values() if r["skill"] == k) for k in (185, 171)},
        "dropped": dropped,
        "gear": len(gear),
        "unused": unused,
        "forever": len(FOREVER_GEAR),
        "food": len(FOOD),
        "lures": len(lures),
        "ranks": len(ranks),
        "enchants": len(enchants),
        "seasons": len(seasons),
        "times": len(TIME_FISH),
    }
    return text, summary


def main():
    try:
        text, summary = build(zs.read_sources(), js.read_sources())
    except zs.DataError as err:
        print("Journal data build failed: %s" % err, file=sys.stderr)
        return 1
    size = len(text.encode("utf-8"))
    if size > MAX_BYTES:
        print("Journal data build failed: %d bytes, budget %d" % (size, MAX_BYTES), file=sys.stderr)
        return 1
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    g = summary["groups"]
    print(
        "Wrote %s: %d bytes; %d items (%s); %d recipes (%d Cooking, %d Alchemy; left out, not on a "
        "Forever skill line: %s); %d Classic gear items (unused, no source: %s) + %d Forever; "
        "%d buff foods; %d lures; %d ranks; %d enchants; %d seasonal fish"
        % (
            os.path.relpath(OUTPUT, ROOT),
            size,
            summary["items"],
            ", ".join("%d %s" % (g[k], k) for k in js.GROUPS),
            summary["recipes"],
            summary["bySkill"][185],
            summary["bySkill"][171],
            ", ".join(str(s) for s in summary["dropped"]) or "none",
            summary["gear"],
            ", ".join(str(u) for u in summary["unused"]) or "none",
            summary["forever"],
            summary["food"],
            summary["lures"],
            summary["ranks"],
            summary["enchants"],
            summary["seasons"],
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
