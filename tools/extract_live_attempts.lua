-- Extracts redacted event sequences from an Epic 1 probe log into spec/fixtures/live_attempts.lua.
-- Usage (repository root): luajit tools/extract_live_attempts.lua probe-results/<log>.lua \
--     spec/fixtures/live_attempts.lua
-- The log is loaded as data in an empty environment. Entry indexes in SCENARIOS refer to the
-- 2026-11-05 06:51 log. Only event names, spell IDs, message types and texts, the loot flag, and
-- channel lengths are written: no names, GUIDs, or cast IDs.
local chunk = assert(loadfile(arg[1]))
local env = {}
setfenv(chunk, env)
chunk()
local entries = env.FishingMasteryProbeDB.log.entries

local SCENARIOS = {
    { "auto loot off: getaway before stop, recast cancels, catches", 1378, 1600 },
    { "auto loot on: catches, getaways, a recast cancel", 1601, 1680 },
    { "early clicks: message before and after the stop", 1683, 1701 },
    { "cancel, two timeouts, and cancels by moving or jumping", 1702, 1749 },
    { "invalid target: no water, too shallow, cast spam", 1750, 1783 },
    { "lure catch: too-shallow recast inside the channel, double LOOT_READY", 2013, 2041 },
    { "non-fishing channel and herb loot", 150, 180 },
    { "non-fishing channel", 940, 950 },
}

local KEEP = {
    UNIT_SPELLCAST_SENT = true,
    UNIT_SPELLCAST_CHANNEL_START = true,
    UNIT_SPELLCAST_CHANNEL_STOP = true,
    UNIT_SPELLCAST_FAILED = true,
    UNIT_SPELLCAST_FAILED_QUIET = true,
    UNIT_SPELLCAST_SUCCEEDED = true,
    UNIT_SPELLCAST_INTERRUPTED = true,
    UNIT_SPELLCAST_START = true,
    UNIT_SPELLCAST_STOP = true,
    UI_INFO_MESSAGE = true,
    UI_ERROR_MESSAGE = true,
    LOOT_READY = true,
    LOOT_OPENED = true,
    LOOT_CLOSED = true,
}
local SPELL_EVENTS = { UNIT_SPELLCAST_SENT = 4 } -- spellID position; others use 3

local function q(s)
    return string.format("%q", s)
end

local out = {}
local function w(s)
    out[#out + 1] = s
end
w("-- Redacted event sequences from the Epic 1 live probe run (2026-11-05, client 1.60.1).")
w("-- Generated by tools/extract_live_attempts.lua; no names, GUIDs, or cast IDs.")
w("-- Each event: { t, event, args..., channel = seconds, fishing = IsFishingLoot() }.")
w("return {")
for _, sc in ipairs(SCENARIOS) do
    local label, from, to = sc[1], sc[2], sc[3]
    local t0
    w("    {")
    w("        label = " .. q(label) .. ",")
    w("        events = {")
    local lastFishing
    for i = from, to do
        local e = entries[i]
        if e.kind == "event" and KEEP[e.data.name] then
            local d = e.data
            t0 = t0 or e.t
            local name = d.name
            local fields = { string.format("%.3f", e.t - t0), q(name) }
            local a = d.args or {}
            if name:find("^UNIT_SPELLCAST") then
                local pos = SPELL_EVENTS[name] or 3
                local spell = a[pos]
                if type(spell) ~= "number" then -- payload table form
                    spell = type(a[2]) == "table" and a[2].spellID or nil
                end
                fields[#fields + 1] = q("player")
                fields[#fields + 1] = "nil"
                fields[#fields + 1] = tostring(spell)
            elseif name == "UI_INFO_MESSAGE" or name == "UI_ERROR_MESSAGE" then
                fields[#fields + 1] = tostring(a[1])
                fields[#fields + 1] = q(a[2])
            elseif name == "LOOT_READY" then
                fields[#fields + 1] = tostring(a[1])
            end
            local extra = ""
            if name == "UNIT_SPELLCAST_CHANNEL_START" then
                for j = i + 1, math.min(i + 3, #entries) do
                    if entries[j].kind == "cast" then
                        extra = ", channel = " .. tostring(entries[j].data.duration)
                        break
                    end
                end
            elseif name == "LOOT_READY" or name == "LOOT_OPENED" then
                for j = i + 1, math.min(i + 3, #entries) do
                    local l = entries[j]
                    if l.kind == "loot" then
                        local v = l.data.isFishingLoot and l.data.isFishingLoot.values
                        lastFishing = v and v[1]
                        break
                    end
                end
                extra = ", fishing = " .. tostring(lastFishing)
            end
            w("            { " .. table.concat(fields, ", ") .. extra .. " },")
        end
    end
    w("        },")
    w("    },")
end
w("}")
local f = assert(io.open(arg[2], "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
