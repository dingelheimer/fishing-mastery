"""Build FishingMastery/Data/Zones.lua from the trimmed sources in tools/data/.

Usage (repository root): python tools/build_zone_data.py

Writes the shared loot lists, each area's base skill, loot list and parent zone, the UI map to
zone table, each zone's subzones, and the dungeon instance table. Fails loudly when an area cannot
be placed or the sources hold something the server logic here does not know. Only numbers, fixed
keys, and sanitized English names in comments are written. Python 3 standard library only.
"""

import os
import re
import sys

from zone_sources import (
    ATT_COMMIT,
    CLIENT_BUILD,
    CMANGOS_COMMIT,
    DataError,
    base_skills,
    complete_lists,
    place_areas,
    read_sources,
    resolve_lists,
)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "FishingMastery", "Data", "Zones.lua")
MAX_BYTES = 50 * 1024
SAFE_NAME = re.compile(r"[^A-Za-z0-9 '\-.,()]")


def comment(text):
    """English name for a comment: a fixed character set, so no text can end the comment."""
    return SAFE_NAME.sub("?", text)[:60]


def number(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise DataError("not a number: %r" % (value,))
    if isinstance(value, int):
        return str(value)
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def version(text, pattern):
    if not re.fullmatch(pattern, text):
        raise DataError("unexpected version text: %r" % text)
    return '"' + text + '"'


def item_text(item):
    item_id, chance, group, condition, quest = item
    fields = [number(item_id), number(chance), number(group), number(condition), "1" if quest else "0"]
    while len(fields) > 3 and fields[-1] == "0":
        fields.pop()
    return "{ " + ", ".join(fields) + " }"


def build(sources):
    lists = resolve_lists(sources)
    skills = base_skills(sources)
    placed = place_areas(sources, set(lists) | set(skills))
    lists, flags = complete_lists(lists, placed)

    # Distinct lists, numbered by the smallest area that uses each.
    order = []
    for area in sorted(lists):
        if lists[area] not in order:
            order.append(lists[area])
    index = {items: i + 1 for i, items in enumerate(order)}

    zones = sorted(a for a, p in placed.items() if p["kind"] == "zone")
    subzones = sorted(a for a, p in placed.items() if p["kind"] == "subzone")
    dungeons = sorted(a for a, p in placed.items() if p["kind"] == "dungeon")

    out = [
        "-- Generated by tools/build_zone_data.py; do not edit. Refresh: see README, Zone Data.",
        "-- Sources: CMaNGOS classic-db %s (GPL-3.0); World of Warcraft: Forever client tables"
        % CMANGOS_COMMIT[:10],
        "-- build %s from the AllTheThings exports %s (MIT)." % (CLIENT_BUILD, ATT_COMMIT[:10]),
        "-- Chances are Classic estimates (CMaNGOS reconstructions), in percent.",
        "local _, ns = ...",
        "",
        "ns.Zones = {",
        "    meta = { cmangos = %s, att = %s, client = %s },"
        % (
            version(CMANGOS_COMMIT[:10], r"[0-9a-f]{10}"),
            version(ATT_COMMIT[:10], r"[0-9a-f]{10}"),
            version(CLIENT_BUILD, r"[0-9.]+"),
        ),
        "    -- Loot lists: { itemID, chance, group, condition, quest }. Group 0 rolls on its own;",
        "    -- other groups give one item per roll. Condition 322 = winter, 323 = summer (game",
        "    -- events 35, 36). Quest 1 = drops only with the quest. Trailing zeros are left out.",
        "    lists = {",
    ]
    for i, items in enumerate(order):
        out.append("        { -- %d" % (i + 1))
        out.extend("            " + item_text(item) + "," for item in items)
        out.append("        },")
    out.append("    },")
    out.append("    -- Areas: base = fishing base skill (nil: the zone's applies), list = loot list (nil: the")
    out.append("    -- zone's applies), merged = subzone extras added to the zone list, partial = percent")
    out.append("    -- of a roll not in the Classic data, zone = parent zone, instance = dungeon map ID.")
    out.append("    areas = {")
    for area in sorted(placed):
        place = placed[area]
        fields = []
        if area in skills:
            fields.append("base = " + number(skills[area]))
        if area in lists:
            fields.append("list = " + number(index[lists[area]]))
            if flags[area]["merged"]:
                fields.append("merged = true")
            if flags[area]["partial"] is not None:
                fields.append("partial = " + number(flags[area]["partial"]))
        if place["kind"] == "subzone":
            fields.append("zone = " + number(place["zone"]))
        if place["kind"] == "dungeon":
            fields.append("instance = " + number(place["instance"]))
        out.append(
            "        [%s] = { %s }, -- %s" % (number(area), ", ".join(fields), comment(place["name"]))
        )
    out.append("    },")
    out.append("    -- UI map ID -> zone area")
    out.append("    mapToArea = {")
    for area in sorted(zones, key=lambda a: placed[a]["map"]):
        out.append(
            "        [%s] = %s, -- %s" % (number(placed[area]["map"]), number(area), comment(placed[area]["name"]))
        )
    out.append("    },")
    out.append("    -- Zone area -> its subzones in the data")
    out.append("    children = {")
    for zone in zones:
        kids = [number(a) for a in subzones if placed[a]["zone"] == zone]
        if kids:
            out.append("        [%s] = { %s }," % (number(zone), ", ".join(kids)))
    out.append("    },")
    out.append("    -- Instance map ID (GetInstanceInfo, 8th return) -> dungeon area")
    out.append("    instanceToArea = {")
    for area in sorted(dungeons, key=lambda a: placed[a]["instance"]):
        out.append(
            "        [%s] = %s, -- %s"
            % (number(placed[area]["instance"]), number(area), comment(placed[area]["name"]))
        )
    out.append("    },")
    out.append("}")
    text = "\n".join(out) + "\n"

    summary = {
        "areas": len(placed),
        "zones": len(zones),
        "subzones": len(subzones),
        "dungeons": len(dungeons),
        "lists": len(order),
        "rows": sum(len(items) for items in order),
        "merged": sum(1 for f in flags.values() if f["merged"]),
        "partial": sum(1 for f in flags.values() if f["partial"] is not None),
    }
    return text, summary


def main():
    try:
        text, summary = build(read_sources())
    except DataError as err:
        print("Zone data build failed: %s" % err, file=sys.stderr)
        return 1
    size = len(text.encode("utf-8"))
    if size > MAX_BYTES:
        print("Zone data build failed: %d bytes, budget %d" % (size, MAX_BYTES), file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(
        "Wrote %s: %d bytes; %d areas (%d zones, %d subzones, %d dungeons), %d loot lists with %d "
        "rows; %d subzones merged with their zone list, %d areas with a partial list"
        % (
            os.path.relpath(OUTPUT, ROOT),
            size,
            summary["areas"],
            summary["zones"],
            summary["subzones"],
            summary["dungeons"],
            summary["lists"],
            summary["rows"],
            summary["merged"],
            summary["partial"],
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
